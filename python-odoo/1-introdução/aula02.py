# Pedido de venda utilizando variáveis

numero_pedido = 1001
cliente = "Mercado São Paulo"
produto = "Leitor de código de barras"
preco_unitario = 350.00
quantidade = 2
produto_ativo = True

total_venda = preco_unitario * quantidade

print("=== PEDIDO DE VENDA ===")
print("Número:", numero_pedido)
print("Cliente:", cliente)
print("Produto:", produto)
print("Preço unitário:", preco_unitario)
print("Quantidade:", quantidade)
print("Produto ativo:", produto_ativo)
print("Total da venda:", total_venda)